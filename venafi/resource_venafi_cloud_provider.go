func buildCreateCloudProviderRequest(d *schema.ResourceData) domain.CreateCloudProviderRequest {
	request := domain.CreateCloudProviderRequest{
		Name:   d.Get(cloudProviderResourceName).(string),
		Type:   domain.GetCloudProviderType(d.Get(cloudProviderResourceType).(string)),
		TeamID: d.Get(cloudProviderResourceTeam).(string),
	}
	if aws := singleBlock(d, cloudProviderResourceAWS); aws != nil {
		request.AWS = &domain.CloudProviderAWSConfiguration{
			AccountID: aws[cloudProviderAWSAccountID].(string),
			Role:      aws[cloudProviderAWSRole].(string),
		}
	}
	if azure := singleBlock(d, cloudProviderResourceAzure); azure != nil {
		request.Azure = &domain.CloudProviderAzureConfiguration{
			ApplicationID: azure[cloudProviderAzureApplicationID].(string),
			DirectoryID:   azure[cloudProviderAzureDirectoryID].(string),
			Secret:        azure[cloudProviderAzureSecret].(string),
		}
	}
	if gcp := singleBlock(d, cloudProviderResourceGCP); gcp != nil {
		request.GCP = &domain.CloudProviderGCPConfiguration{
			ServiceAccountEmail:            gcp[cloudProviderGCPServiceAccountEmail].(string),
			ProjectNumber:                  gcp[cloudProviderGCPProjectNumber].(string),
			WorkloadIdentityPoolID:         gcp[cloudProviderGCPWorkloadIdentityPoolID].(string),
			WorkloadIdentityPoolProviderID: gcp[cloudProviderGCPWorkloadIdentityPoolProviderID].(string),
			AuthorizationMethod:            domain.GetGCPAuthorizationMethod(gcp[cloudProviderGCPAuthorizationMethod].(string)),
		}
	}
	return request
}

// buildUpdateCloudProviderRequest returns the changes to apply, or nil when
// none of the updatable attributes changed
func buildUpdateCloudProviderRequest(d *schema.ResourceData) *domain.UpdateCloudProviderRequest {
	request := &domain.UpdateCloudProviderRequest{
		ID:   d.Id(),
		Type: domain.GetCloudProviderType(d.Get(cloudProviderResourceType).(string)),
	}
	changed := false

	if d.HasChange(cloudProviderResourceName) {
		name := d.Get(cloudProviderResourceName).(string)
		request.Name = &name
		changed = true
	}
	if d.HasChange(cloudProviderResourceTeam) {
		if team := d.Get(cloudProviderResourceTeam).(string); team != "" {
			request.TeamID = &team
			changed = true
		}
	}
	if d.HasChange(cloudProviderResourceAWS) {
		if aws := singleBlock(d, cloudProviderResourceAWS); aws != nil {
			role := aws[cloudProviderAWSRole].(string)
			request.AWS = &domain.CloudProviderAWSConfigurationUpdate{Role: &role}
			changed = true
		}
	}
	if d.HasChange(cloudProviderResourceAzure) {
		if azure := singleBlock(d, cloudProviderResourceAzure); azure != nil {
			applicationID := azure[cloudProviderAzureApplicationID].(string)
			directoryID := azure[cloudProviderAzureDirectoryID].(string)
			// the API requires the secret with every Azure configuration update
			request.Azure = &domain.CloudProviderAzureConfigurationUpdate{
				ApplicationID: &applicationID,
				DirectoryID:   &directoryID,
				Secret:        azure[cloudProviderAzureSecret].(string),
			}
			changed = true
		}
	}
	if d.HasChange(cloudProviderResourceGCP) {
		if gcp := singleBlock(d, cloudProviderResourceGCP); gcp != nil {
			request.GCP = &domain.CloudProviderGCPConfigurationUpdate{
				ProjectNumber:                  optionalString(gcp[cloudProviderGCPProjectNumber].(string)),
				WorkloadIdentityPoolID:         optionalString(gcp[cloudProviderGCPWorkloadIdentityPoolID].(string)),
				WorkloadIdentityPoolProviderID: optionalString(gcp[cloudProviderGCPWorkloadIdentityPoolProviderID].(string)),
				AuthorizationMethod:            domain.GetGCPAuthorizationMethod(gcp[cloudProviderGCPAuthorizationMethod].(string)),
			}
			changed = true
		}
	}

	if !changed {
		return nil
	}
	return request
}

func storeCloudProviderInState(provider *domain.CloudProvider, d *schema.ResourceData) error {
	d.SetId(provider.ID)
	values := map[string]interface{}{
		cloudProviderResourceName:           provider.Name,
		cloudProviderResourceType:           provider.Type.String(),
		cloudProviderResourceStatus:         provider.Status.String(),
		cloudProviderResourceStatusDetails:  provider.StatusDetails,
		cloudProviderResourceKeystoresCount: provider.KeystoresCount,
	}
	if provider.AWS != nil {
		values[cloudProviderResourceAWS] = []interface{}{map[string]interface{}{
			cloudProviderAWSAccountID:  provider.AWS.AccountID,
			cloudProviderAWSRole:       provider.AWS.Role,
			cloudProviderAWSExternalID: provider.AWS.ExternalID,
		}}
	}
	if provider.Azure != nil {
		// The API never returns the secret, so keep the one already in state
		secret := ""
		if azure := singleBlock(d, cloudProviderResourceAzure); azure != nil {
			secret, _ = azure[cloudProviderAzureSecret].(string)
		}
		values[cloudProviderResourceAzure] = []interface{}{map[string]interface{}{
			cloudProviderAzureApplicationID: provider.Azure.ApplicationID,
			cloudProviderAzureDirectoryID:   provider.Azure.DirectoryID,
			cloudProviderAzureSecret:        secret,
		}}
	}
	if provider.GCP != nil {
		authorizationMethod := ""
		if provider.GCP.AuthorizationMethod != domain.GCPAuthorizationMethodUnknown {
			authorizationMethod = provider.GCP.AuthorizationMethod.String()
		}
		values[cloudProviderResourceGCP] = []interface{}{map[string]interface{}{
			cloudProviderGCPServiceAccountEmail:            provider.GCP.ServiceAccountEmail,
			cloudProviderGCPProjectNumber:                  provider.GCP.ProjectNumber,
			cloudProviderGCPWorkloadIdentityPoolID:         provider.GCP.WorkloadIdentityPoolID,
			cloudProviderGCPWorkloadIdentityPoolProviderID: provider.GCP.WorkloadIdentityPoolProviderID,
			cloudProviderGCPAuthorizationMethod:            authorizationMethod,
			cloudProviderGCPPublicKey:                      provider.GCP.PublicKey,
			cloudProviderGCPIssuerURL:                      provider.GCP.IssuerURL,
		}}
	}
	return setAll(d, values)
}

func resourceCloudProviderCreate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	request := buildCreateCloudProviderRequest(d)
	logFields := map[string]interface{}{cloudProviderResourceName: request.Name, cloudProviderResourceType: request.Type.String()}
	tflog.Info(ctx, "creating cloud provider", logFields)

	manager, _, err := getCloudProviderManager(ctx, meta, resourceVenafiCloudProviderName)
	if err != nil {
		return diag.FromErr(err)
	}

	provider, err := manager.CreateCloudProvider(request)
	if err != nil {
		return diag.FromErr(err)
	}
	if err := storeCloudProviderInState(provider, d); err != nil {
		return diag.FromErr(err)
	}

	logFields["id"] = provider.ID
	tflog.Info(ctx, "cloud provider created", logFields)
	return nil
}

func resourceCloudProviderRead(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	logFields := map[string]interface{}{"id": d.Id()}
	tflog.Info(ctx, "reading cloud provider", logFields)

	manager, _, err := getCloudProviderManager(ctx, meta, resourceVenafiCloudProviderName)
	if err != nil {
		return diag.FromErr(err)
	}

	provider, err := findCloudProviderByID(manager, d.Id())
	if err != nil {
		return diag.FromErr(err)
	}
	if provider == nil {
		tflog.Info(ctx, "cloud provider not found, removing it from state", logFields)
		d.SetId("")
		return nil
	}

	if err := storeCloudProviderInState(provider, d); err != nil {
		return diag.FromErr(err)
	}
	tflog.Info(ctx, "cloud provider read", logFields)
	return nil
}

func resourceCloudProviderUpdate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	logFields := map[string]interface{}{"id": d.Id()}
	tflog.Info(ctx, "updating cloud provider", logFields)

	request := buildUpdateCloudProviderRequest(d)
	if request == nil {
		return resourceCloudProviderRead(ctx, d, meta)
	}

	manager, _, err := getCloudProviderManager(ctx, meta, resourceVenafiCloudProviderName)
	if err != nil {
		return diag.FromErr(err)
	}

	provider, err := manager.UpdateCloudProvider(*request)
	if err != nil {
		return diag.FromErr(err)
	}
	if err := storeCloudProviderInState(provider, d); err != nil {
		return diag.FromErr(err)
	}
	tflog.Info(ctx, "cloud provider updated", logFields)
	return nil
}

func resourceCloudProviderDelete(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	logFields := map[string]interface{}{"id": d.Id()}
	tflog.Info(ctx, "deleting cloud provider", logFields)

	manager, _, err := getCloudProviderManager(ctx, meta, resourceVenafiCloudProviderName)
	if err != nil {
		return diag.FromErr(err)
	}

	if err := manager.DeleteCloudProvider(d.Id()); err != nil {
		return diag.FromErr(err)
	}

	d.SetId("")
	tflog.Info(ctx, "cloud provider deleted", logFields)
	return nil
}
